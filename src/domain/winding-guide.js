export const WINDING_MATERIAL = Object.freeze({
  MONO: 'mono',
  FLUORO: 'fluoro',
  BRAID: 'braid',
});

const COMMON_STEPS = [
  'Проверьте, что шпуля установлена правильно, а ролик лесоукладывателя вращается свободно.',
  'Пропустите материал через первое кольцо удилища и откройте дужку лесоукладывателя перед креплением к шпуле.',
  'Наматывайте с умеренным и стабильным натяжением. Универсального значения силы натяжения для всех материалов нет.',
  'Первые десятки оборотов делайте медленно и следите, чтобы укладка оставалась ровной.',
];

export function buildWindingGuide({ material, hasBacking = false } = {}) {
  if (!Object.values(WINDING_MATERIAL).includes(material)) throw new RangeError('unsupported winding material');

  const steps = [...COMMON_STEPS];
  const checks = [];
  const warnings = [];

  if (hasBacking) {
    steps.unshift('Если точное количество бэкинга неизвестно, используйте метод обратной намотки: сначала основная леска на запасную шпулю, затем бэкинг до нужного уровня, после чего перемотайте всё на рабочую шпулю.');
  }

  if (material === WINDING_MATERIAL.MONO || material === WINDING_MATERIAL.FLUORO) {
    steps.push('Подавайте леску с упаковочной шпули плашмя и после нескольких оборотов ослабьте леску, чтобы проверить образование петель.');
    steps.push('Если свободная леска начинает сильнее скручиваться и собираться петлями, переверните упаковочную шпулю другой стороной и повторите проверку.');
    checks.push('Через несколько десятков оборотов остановитесь и ослабьте леску. Она не должна резко закручиваться в крупные петли.');
    warnings.push('Для монофильной лески (mono) и флюорокарбона (fluorocarbon) направление схода с упаковочной шпули влияет на перекручивание. Проверяйте его по фактическому поведению лески.');
  }

  if (material === WINDING_MATERIAL.BRAID) {
    steps.push('Для плетёного шнура (braid) сначала проверьте инструкцию производителя: способ подачи и рекомендуемое натяжение могут отличаться.');
    steps.push('Не допускайте свободных мягких витков: плетёнка должна ложиться равномерно и достаточно плотно, но без чрезмерного натяжения.');
    checks.push('Проведите пальцем по верхним слоям: витки не должны проваливаться внутрь намотки при лёгком нажатии.');
    warnings.push('Для плетёного шнура нет универсального правила подачи, которое заменяет инструкцию конкретного производителя.');
  }

  steps.push('Остановитесь до полного заполнения и сравните уровень лески с рекомендацией производителя катушки.');
  steps.push('Если инструкция катушки не задаёт уровень явно, начните с ориентировочного зазора около 2–3 мм до бортика и проверьте работу на практике.');
  checks.push('После намотки прокрутите катушку и осмотрите профиль: выраженный конус, ямы по краям или провалы требуют проверки укладки и, возможно, регулировки шпули.');
  checks.push('Перед рыбалкой сделайте несколько пробных забросов в безопасном месте и убедитесь, что леска не сбрасывает лишние петли и не врезается в нижние слои.');
  warnings.push('Зазор у бортика не имеет одного универсального стандарта для всех катушек. Приоритет всегда у инструкции конкретной модели.');
  warnings.push('Мастер не диагностирует механические неисправности катушки. Если укладка остаётся явно неправильной после проверки намотки, нужна отдельная диагностика ролика, шпули и регулировочных шайб.');

  return { material, hasBacking: Boolean(hasBacking), steps, checks, warnings };
}
